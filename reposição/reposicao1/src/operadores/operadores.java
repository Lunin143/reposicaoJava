package operadores;

public class operadores {

    public double valor1;
    public double valor2;

    public double adicao() {

        return valor1 + valor2;

    }

    public double subtracao() {

        return valor1 - valor2;

    }

    public double divisao() {

      return valor1 / valor2;

    }

    public double multiplicacao() {

        return valor1 * valor2;

    }

}